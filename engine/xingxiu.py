def get_xingxiu(lunar_month, lunar_day):
    """根據農曆月日查本命星宿
    
    Args:
        lunar_month: 農曆月份 (1-12)
        lunar_day: 農曆日期 (1-30)
    
    Returns:
        str: 星宿名稱（如 '奎'）
    """
    if not (1 <= lunar_month <= 12):
        return '未知'
    if not (1 <= lunar_day <= 30):
        return '未知'
    return XINGXIU_TABLE[lunar_day - 1][lunar_month - 1]


def relation(x1, x2):
    """計算兩個星宿的關係類型
    
    Args:
        x1: 第一個星宿名稱
        x2: 第二個星宿名稱
    
    Returns:
        str: 關係類型（命之星/業胎/安壞/榮親/友衰/危成/鄰近）
    """
    try:
        idx1 = XINGXIU.index(x1)
        idx2 = XINGXIU.index(x2)
    except ValueError:
        return '未知'
    
    d = (idx2 - idx1) % 28
    
    if d == 0:
        return '命之星'
    elif d in [1, 27]:
        return '業胎'
    elif d in [2, 3, 25, 26]:
        return '安壞'
    elif d in [4, 5, 23, 24]:
        return '榮親'
    elif d in [6, 7, 21, 22]:
        return '友衰'
    elif d in [8, 9, 10, 11, 12, 13, 15, 16, 17, 18, 19, 20]:
        return '危成'
    elif d == 14:
        return '命之星'
    else:
        return '鄰近'


def relation_detail(x1, x2):
    """取得星宿關係的詳細描述
    
    Returns:
        dict: 包含 description, dynamics, advice
    """
    rel = relation(x1, x2)
    return XINGXIU_RELATION_DETAILS.get(rel, XINGXIU_RELATION_DETAILS['鄰近'])


def xingxiu_group(xingxiu_name):
    """取得星宿所屬的象（四象）
    
    Returns:
        str: 東方青龍/北方玄武/西方白虎/南方朱雀
    """
    idx = XINGXIU.index(xingxiu_name)
    if idx < 7:
        return '東方青龍'
    elif idx < 14:
        return '北方玄武'
    elif idx < 21:
        return '西方白虎'
    else:
        return '南方朱雀'


